def search_tmdb_movie(query):
    if query.isdigit():
        url = f"https://api.themoviedb.org/3/movie/{query}?api_key={TMDB_API_KEY}"
        response = requests.get(url)
        return [response.json()] if response.status_code == 200 else None

    url = f"https://api.themoviedb.org/3/search/movie?api_key={TMDB_API_KEY}&query={query}&include_adult=false"
    response = requests.get(url)
    if response.status_code == 200:
        results = response.json().get('results', [])
        if results:
            exact_matches = [r for r in results if r['title'].lower() == query.lower()]
            if exact_matches:
                return exact_matches
            return sorted(results, key=lambda x: x['popularity'], reverse=True)
    return None


