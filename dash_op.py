def download_video(url, user_folder):
    parsed_url = urlparse(url)
    domain = parsed_url.netloc.lower()
    print(f"Analyzing URL: {url}")

    if url.lower().endswith(('.mp4', '.mkv', '.mov', '.webm')):
        return download_direct_file(url, user_folder)

    ytdlp_domains = ['youtube.com', 'youtu.be', 'vimeo.com', 'dailymotion.com',
                      'twitch.tv', 'facebook.com', 'fb.watch', 'instagram.com',
                      'tiktok.com', 'twitter.com', 'x.com']
    if any(d in domain for d in ytdlp_domains):
        return download_with_ytdlp(url, user_folder)
    elif 'drive.google.com' in domain:
        return download_google_drive(url, user_folder)
    elif 'm3u8' in url.lower():
        return download_m3u8(url, user_folder)
    elif re.search(r'(mp4|mkv|mov|webm)', url.lower()):
        return download_direct_file(url, user_folder)
    else:
        return download_with_ytdlp(url, user_folder)


def download_google_drive(url, user_folder):
    print("Using Google Drive downloader...")
    file_id = re.search(r'[-\w]{25,}', url)
    if file_id:
        gdown.download(f'https://drive.google.com/uc?id={file_id.group(0)}',
                        os.path.join(user_folder, "input.mp4"), quiet=False)
        return os.path.join(user_folder, "input.mp4")
    print("Invalid Google Drive URL.")
    return None


def download_with_ytdlp(url, user_folder):
    print("Using yt-dlp downloader...")
    ydl_opts = {
        'outtmpl': f'{user_folder}/input.%(ext)s',
        'progress_hooks': [progress_hook],
        'format': 'bestvideo+bestaudio/best',
        'quiet': False,
        'no_warnings': False,
        'ignoreerrors': True,
        'concurrent_fragment_downloads': 8,   # speed: parallel fragment downloads
    }
    try:
        with yt_dlp.YoutubeDL(ydl_opts) as ydl:
            info_dict = ydl.extract_info(url, download=True)
            original_file = ydl.prepare_filename(info_dict)
            new_file = os.path.join(user_folder, "input.mkv")
            os.rename(original_file, new_file)
            return new_file
    except Exception as e:
        print(f"Error downloading video with yt-dlp: {str(e)}")
        return None


def download_direct_file(url, user_folder):
    print("Using direct file downloader...")
    output_file = os.path.join(user_folder, "input.mkv")
    try:
        with requests.get(url, stream=True) as r:
            r.raise_for_status()
            total_size = int(r.headers.get('content-length', 0))
            block_size = 1024 * 1024  # 1MB chunks: fewer syscalls, faster
            downloaded = 0
            with open(output_file, 'wb') as f:
                for chunk in r.iter_content(chunk_size=block_size):
                    if chunk:
                        f.write(chunk)
                        downloaded += len(chunk)
                        if total_size > 0:
                            percent = (downloaded / total_size) * 100
                            print(f"\rDownloading: {percent:.1f}%", end='')
        print("\nDirect download complete.")
        return output_file
    except Exception as e:
        print(f"Error downloading direct file: {str(e)}")
        return None


def download_m3u8(url, user_folder):
    print("Using m3u8/HLS downloader...")
    output_file = os.path.join(user_folder, "input.mkv")
    try:
        cmd = ["ffmpeg", "-y", "-i", url, "-c", "copy", "-bsf:a", "aac_adtstoasc", output_file]
        process = subprocess.Popen(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                                    universal_newlines=True)
        process.wait()
        if process.returncode == 0:
            print("\nM3U8 download complete.")
            return output_file
        print(f"\nError downloading M3U8 stream. Return code: {process.returncode}")
        return None
    except Exception as e:
        print(f"Error downloading M3U8: {str(e)}")
        return None


