UPLOAD_EXTENSIONS = ('.m4s', '.m4a', '.webm', '.mp3', '.ac3', '.eac3', '.ogg',
                      '.flac', '.mka', '.wav', '.pcm', '.dts', '.thd', '.amr',
                      '.html', '.mpd', '.vtt')


def _make_sftp_client():
    transport = paramiko.Transport((SFTP_HOST, SFTP_PORT))
    private_key = paramiko.RSAKey.from_private_key_file(PRIVATE_KEY_PATH)
    transport.connect(username=SFTP_USERNAME, pkey=private_key)
    sftp = paramiko.SFTPClient.from_transport(transport)
    return transport, sftp


def upload_files_to_sftp(local_folder, folder_id):
    """Upload all files in parallel using multiple SFTP connections for speed."""
    remote_folder_path = os.path.join(REMOTE_BASE_PATH, folder_id).replace("\\\\", "/")

    # Ensure remote directory exists (single connection, one-time setup)
    transport, sftp = _make_sftp_client()
    try:
        sftp.chdir(remote_folder_path)
    except IOError:
        sftp.mkdir(remote_folder_path)
    sftp.close()
    transport.close()

    files_to_upload = [
        os.path.join(root, f)
        for root, _, files in os.walk(local_folder)
        for f in files if f.endswith(UPLOAD_EXTENSIONS)
    ]
    total_files = len(files_to_upload)
    uploaded_files = [0]

    def upload_one(local_file_path):
        transport, sftp = _make_sftp_client()
        try:
            remote_file_path = os.path.join(remote_folder_path, os.path.basename(local_file_path)).replace("\\\\", "/")
            sftp.put(local_file_path, remote_file_path)
        finally:
            sftp.close()
            transport.close()
        uploaded_files[0] += 1
        print(f"\rUploaded {uploaded_files[0]}/{total_files} files", end='')

    with ThreadPoolExecutor(max_workers=min(UPLOAD_WORKERS, max(1, total_files))) as executor:
        futures = [executor.submit(upload_one, f) for f in files_to_upload]
        for future in as_completed(futures):
            future.result()

    print("\nUpload complete.")
    mpd_link = f"{BASE_URL}{folder_id}/output.mpd"
    html_link = f"{BASE_URL}{folder_id}/stream.html"
    print(f"MPD-Link: {mpd_link}")
    print(f"HTML-Link: {html_link}")


