def extract_subtitle_tracks(user_folder, input_video):
    info = get_video_info(input_video)
    if not has_subtitle_streams(info):
        print("No subtitle tracks found in the video.")
        return []

    lang_count = {}
    jobs = []

    for stream in info.get("streams", []):
        if stream.get("codec_type") == "subtitle":
            index = stream.get("index")
            original_lang = stream.get("tags", {}).get("language", f"und_{index}")

            if original_lang in lang_count:
                lang_count[original_lang] += 1
                file_lang = f"{original_lang}{lang_count[original_lang]}"
            else:
                lang_count[original_lang] = 0
                file_lang = original_lang

            print(f"Subtitle track {index} detected with language: {original_lang}.")
            subtitle_file = f"{user_folder}/{file_lang}.vtt"

            display_name = LANGUAGE_MAP.get(original_lang.split('_')[0], original_lang)
            if lang_count[original_lang] > 0:
                display_name = f"{display_name} {lang_count[original_lang] + 1}"

            jobs.append((index, subtitle_file, original_lang, display_name))

    subtitle_tracks = [None] * len(jobs)

    def run_job(job_idx, index, subtitle_file, original_lang, display_name):
        subprocess.run(["ffmpeg", "-y", "-i", input_video, "-map", f"0:{index}", subtitle_file],
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        return job_idx, (subtitle_file, original_lang, display_name)

    with ThreadPoolExecutor(max_workers=min(4, max(1, len(jobs)))) as executor:
        futures = [executor.submit(run_job, i, *job) for i, job in enumerate(jobs)]
        for future in as_completed(futures):
            job_idx, result = future.result()
            subtitle_tracks[job_idx] = result

    return subtitle_tracks


# ================= VIDEO TRANSCODE (GPU-accelerated with fallback) =================
def _run_ffmpeg_with_progress(cmd, label="Processing"):
    process = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                universal_newlines=True)
    duration = None
    for line in process.stdout:
        if duration is None and "Duration" in line:
            m = re.search(r"Duration: (\d+):(\d+):(\d+)", line)
            if m:
                h, mm, s = map(int, m.groups())
                duration = h * 3600 + mm * 60 + s
        if duration and "time=" in line:
            m = re.search(r"time=(\d+):(\d+):(\d+)", line)
            if m:
                h, mm, s = map(int, m.groups())
                current_time = h * 3600 + mm * 60 + s
                progress = min(100, int(current_time / duration * 100)) if duration else 0
                bar_length = 30
                filled = int(bar_length * progress / 100)
                bar = "#" * filled + "-" * (bar_length - filled)
                print(f"\r{label}: [{bar}] {progress}% complete", end='')
    process.wait()
    print()
    return process.returncode


def create_no_audio_video(user_folder, input_video):
    """Create a no-audio version, using GPU (NVENC) transcode for HEVC when available,
    falling back to a fast CPU preset. Non-HEVC videos are stream-copied (fastest)."""
    no_audio_video = f"{user_folder}/input1.mp4"

    if is_hevc_video(input_video):
        print("HEVC/H.265 video detected. Converting to H.264...")
        if USE_GPU_ENCODING:
            gpu_cmd = ["ffmpeg", "-y", "-i", input_video, "-c:v", "h264_nvenc",
                       "-preset", "p4", "-cq", "23", "-an", no_audio_video]
            returncode = _run_ffmpeg_with_progress(gpu_cmd, "GPU Transcoding")
            if returncode == 0:
                print("Converted using GPU (NVENC) acceleration.")
                return no_audio_video
            print("GPU encoding unavailable/failed, falling back to CPU...")

        cpu_cmd = ["ffmpeg", "-y", "-i", input_video, "-c:v", "libx264",
                   "-preset", "veryfast", "-crf", "23", "-threads", FFMPEG_THREADS,
                   "-an", no_audio_video]
        _run_ffmpeg_with_progress(cpu_cmd, "CPU Transcoding")
        print("Converted HEVC/H.265 to H.264 and removed audio.")
    else:
        print("Creating version with no audio (codec copy)...")
        subprocess.run(["ffmpeg", "-y", "-i", input_video, "-c:v", "copy", "-an", no_audio_video],
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        print("Created no-audio version with original codec.")

    return no_audio_video


def encode_to_dash(user_folder, no_audio_video, audio_tracks):
    print("Encoding video to DASH format...")
    video_dash = f"{user_folder}/output.mpd"

    command = ["ffmpeg", "-y", "-i", no_audio_video]
    for audio_file, _ in audio_tracks:
        command.extend(["-i", audio_file])

    command.extend(["-map", "0:v:0", "-c:v", "copy"])

    for i, (audio_file, lang) in enumerate(audio_tracks):
        if audio_file.endswith('.opus'):
            codec = "libopus"
        elif audio_file.endswith('.mp3'):
            codec = "libmp3lame"
        else:
            codec = "aac"
        command.extend(["-map", f"{i+1}:a:0", "-c:a", codec, "-threads", FFMPEG_THREADS,
                         f"-metadata:s:a:{i}", f"language={lang}"])

    command.extend(["-f", "dash", video_dash])

    print("Generated ffmpeg command:")
    print(" ".join(command))
    print("\nStarting DASH encoding with progress...")

    returncode = _run_ffmpeg_with_progress(command, "DASH Encoding")

    if returncode == 0:
        print("DASH encoding complete.")
        return video_dash
    print("Error during DASH encoding.")
    return None


