def extract_audio_tracks(user_folder, input_video):
    """Extract all audio tracks in parallel threads (ffmpeg is I/O + CPU bound,
    running multiple simultaneously speeds up multi-track videos significantly)."""
    info = get_video_info(input_video)
    lang_count = {}
    jobs = []

    for stream in info.get("streams", []):
        if stream.get("codec_type") == "audio":
            index = stream.get("index")
            lang = stream.get("tags", {}).get("language", f"und_{index}")
            codec_name = stream.get("codec_name", "aac")

            if lang in lang_count:
                lang_count[lang] += 1
                audio_file = f"{user_folder}/{lang}_{lang_count[lang]}.{codec_name}"
            else:
                lang_count[lang] = 0
                audio_file = f"{user_folder}/{lang}.{codec_name}"

            print(f"Audio track {index} detected with language: {lang} and codec: {codec_name}.")
            jobs.append((index, lang, codec_name, audio_file))

    audio_tracks = [None] * len(jobs)

    def run_job(job_idx, index, lang, codec_name, audio_file):
        if codec_name.lower() == "eac3":
            out_file = audio_file.replace(f".{codec_name}", ".aac")
            cmd = ["ffmpeg", "-y", "-i", input_video, "-map", f"0:{index}",
                   "-c:a", "aac", "-b:a", "192k", "-threads", FFMPEG_THREADS, out_file]
            subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            return job_idx, (out_file, lang)
        else:
            cmd = ["ffmpeg", "-y", "-i", input_video, "-map", f"0:{index}",
                   "-c:a", "copy", audio_file]
            subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            return job_idx, (audio_file, lang)

    with ThreadPoolExecutor(max_workers=min(4, max(1, len(jobs)))) as executor:
        futures = [executor.submit(run_job, i, *job) for i, job in enumerate(jobs)]
        for future in as_completed(futures):
            job_idx, result = future.result()
            audio_tracks[job_idx] = result

    return audio_tracks


